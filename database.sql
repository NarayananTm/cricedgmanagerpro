
-- 1. Users
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    plan TEXT DEFAULT 'starter',
    is_admin SMALLINT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Tournaments
CREATE TABLE IF NOT EXISTS tournaments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    sport TEXT DEFAULT 'cricket',
    format TEXT NOT NULL,
    overs INTEGER NOT NULL,
    teams_count INTEGER NOT NULL,
    status TEXT DEFAULT 'draft',
    is_auction_enabled SMALLINT DEFAULT 0,
    base_budget INTEGER DEFAULT 10000000,
    sport_options TEXT,
    start_date TEXT,
    end_date TEXT,
    rules TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Teams
CREATE TABLE IF NOT EXISTS teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER,
    name TEXT NOT NULL,
    short_name TEXT,
    logo_url TEXT,
    manager_name TEXT,
    payment_status TEXT DEFAULT 'pending',
    status TEXT DEFAULT 'pending',
    remaining_budget INTEGER DEFAULT 0,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

-- 4. Players
CREATE TABLE IF NOT EXISTS players (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INTEGER,
    tournament_id INTEGER,
    name TEXT NOT NULL,
    age INTEGER,
    role TEXT,
    base_price INTEGER DEFAULT 0,
    sold_price INTEGER DEFAULT 0,
    is_sold SMALLINT DEFAULT 0,
    image_url TEXT,
    phone TEXT,
    sport TEXT,
    sport_details TEXT,
    FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE SET NULL,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

-- 5. Matches
CREATE TABLE IF NOT EXISTS matches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER,
    team1_id INTEGER,
    team2_id INTEGER,
    venue TEXT,
    match_date TIMESTAMP,
    status TEXT DEFAULT 'scheduled',
    winner_id INTEGER,
    toss_winner_id INTEGER,
    toss_decision TEXT,
    current_innings INTEGER DEFAULT 1,
    live_stream_url TEXT,
    striker_id INTEGER,
    non_striker_id INTEGER,
    bowler_id INTEGER,
    team1_score INTEGER DEFAULT 0,
    team2_score INTEGER DEFAULT 0,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE,
    FOREIGN KEY (team1_id) REFERENCES teams(id) ON DELETE SET NULL,
    FOREIGN KEY (team2_id) REFERENCES teams(id) ON DELETE SET NULL
);

-- 6. Innings
CREATE TABLE IF NOT EXISTS innings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER,
    innings_number INTEGER,
    batting_team_id INTEGER,
    bowling_team_id INTEGER,
    runs INTEGER DEFAULT 0,
    wickets INTEGER DEFAULT 0,
    overs_bowled REAL DEFAULT 0.0,
    FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE
);

-- 7. Balls
CREATE TABLE IF NOT EXISTS balls (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    innings_id INTEGER,
    over_number INTEGER,
    ball_number INTEGER,
    batsman_id INTEGER,
    bowler_id INTEGER,
    runs INTEGER,
    extras INTEGER DEFAULT 0,
    extra_type TEXT,
    wicket_type TEXT,
    wicket_player_id INTEGER,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (innings_id) REFERENCES innings(id) ON DELETE CASCADE
);

-- 8. Points table
CREATE TABLE IF NOT EXISTS points_table (
    tournament_id INTEGER,
    team_id INTEGER,
    played INTEGER DEFAULT 0,
    won INTEGER DEFAULT 0,
    lost INTEGER DEFAULT 0,
    tied INTEGER DEFAULT 0,
    nrr REAL DEFAULT 0.0,
    points INTEGER DEFAULT 0,
    PRIMARY KEY (tournament_id, team_id),
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE,
    FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE
);

-- 9. Match events
CREATE TABLE IF NOT EXISTS match_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    event_type TEXT NOT NULL,
    team_id INTEGER,
    player_id INTEGER,
    description TEXT,
    FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE
);

-- 10. Expenses
CREATE TABLE IF NOT EXISTS expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER,
    description TEXT NOT NULL,
    amount INTEGER NOT NULL,
    category TEXT,
    date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

-- 11. Products
CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    price REAL NOT NULL,
    image_url TEXT,
    selling_options TEXT,
    stock INTEGER DEFAULT 0,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 12. Orders
CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER,
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_mobile TEXT NOT NULL,
    customer_address TEXT NOT NULL,
    quantity INTEGER DEFAULT 1,
    total_price REAL NOT NULL,
    status TEXT DEFAULT 'pending',
    payment_method TEXT,
    payment_details TEXT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
);

-- 13. Grounds
CREATE TABLE IF NOT EXISTS grounds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT NOT NULL,
    description TEXT,
    price_per_hour REAL NOT NULL,
    image_url TEXT,
    amenities TEXT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 14. Ground bookings
CREATE TABLE IF NOT EXISTS ground_bookings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ground_id INTEGER,
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_mobile TEXT NOT NULL,
    booking_date DATE NOT NULL,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    total_price REAL NOT NULL,
    status TEXT DEFAULT 'pending',
    payment_method TEXT,
    payment_details TEXT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ground_id) REFERENCES grounds(id) ON DELETE SET NULL
);

-- 15. Sponsors
CREATE TABLE IF NOT EXISTS sponsors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER,
    name TEXT NOT NULL,
    website_url TEXT,
    banner_url TEXT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

-- 16. Settings
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

-- 17. Team chats
CREATE TABLE IF NOT EXISTS team_chats (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER NOT NULL,
    sender_name TEXT NOT NULL,
    team_name TEXT NOT NULL,
    message TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

-- 18. Tournament gallery
CREATE TABLE IF NOT EXISTS tournament_gallery (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER NOT NULL,
    image_url TEXT NOT NULL,
    caption TEXT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

-- 19. Auction invites
CREATE TABLE IF NOT EXISTS auction_invites (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER NOT NULL,
    player_name TEXT,
    email TEXT,
    phone TEXT,
    sport TEXT DEFAULT 'cricket',
    notes TEXT,
    invite_code TEXT UNIQUE NOT NULL,
    status TEXT DEFAULT 'pending',
    registered_player_id INTEGER,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE
);

